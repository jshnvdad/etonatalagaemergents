using System.ComponentModel.DataAnnotations;

namespace EmergencyDesk.Server.Data;

public enum IncidentType { Medical, Fire, Police, Rescue }
public enum IncidentStatus { Received, Dispatched, EnRoute, OnScene, Resolved, Cancelled }
public enum ResponderStatus { Available, Busy, OffDuty }

/// <summary>Admins and dispatchers who sign in to the desktop app.</summary>
public class Staff
{
    public int Id { get; set; }
    [MaxLength(60)] public string Username { get; set; } = "";
    public string PasswordHash { get; set; } = "";
    [MaxLength(100)] public string DisplayName { get; set; } = "";
    /// <summary>"Admin" or "Dispatcher"</summary>
    [MaxLength(20)] public string Role { get; set; } = "Dispatcher";
}

/// <summary>People who use the mobile app.</summary>
public class AppUser
{
    public int Id { get; set; }
    [MaxLength(100)] public string FullName { get; set; } = "";
    [MaxLength(150)] public string Email { get; set; } = "";
    [MaxLength(40)] public string Phone { get; set; } = "";
    public string PasswordHash { get; set; } = "";
    public bool IsActive { get; set; } = true;
    public DateTime RegisteredAt { get; set; } = DateTime.UtcNow;
}

public class Responder
{
    public int Id { get; set; }
    [MaxLength(100)] public string Name { get; set; } = "";
    [MaxLength(60)] public string Unit { get; set; } = "";
    public IncidentType Specialty { get; set; }
    public ResponderStatus Status { get; set; } = ResponderStatus.Available;
    [MaxLength(40)] public string Phone { get; set; } = "";
}

public class Incident
{
    public int Id { get; set; }
    /// <summary>Generated by the phone. Used so a retried upload never creates a duplicate.</summary>
    [MaxLength(64)] public string ClientId { get; set; } = "";
    public int UserId { get; set; }
    public AppUser? User { get; set; }
    public IncidentType Type { get; set; }
    public IncidentStatus Status { get; set; } = IncidentStatus.Received;
    [MaxLength(1000)] public string Description { get; set; } = "";
    public double? Latitude { get; set; }
    public double? Longitude { get; set; }
    [MaxLength(300)] public string? Address { get; set; }
    public DateTime ReportedAt { get; set; } = DateTime.UtcNow;
    public int? AssignedResponderId { get; set; }
    public Responder? AssignedResponder { get; set; }
}
